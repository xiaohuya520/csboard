// cs_app.h —— CS 赛事看板界面与按键状态机。
//
// 架构(针对旧固件"双击弹回原页"):
//   按键回调**只修改极小的状态**(当前页 / 选中项 / 待刷新标志),绝不直接建/删对象、
//   也绝不做"按某个索引重新进入某一页"这种状态相关的跳转。渲染由一个 200ms 的
//   LVGL 定时器按状态重建。于是驱动多报一个 CLICK 的最坏后果只是"多请求一次刷新",
//   不可能把页面弹回去 —— 从设计上消除,而不是靠时间冷却硬扛。
#pragma once

#include "bsp_button.h"

// 建屏并启动刷新定时器。需在持有 LVGL 锁的情况下调用(main.c)。
void cs_app_start(void);

// 按键入口(在持有 LVGL 锁的按键任务里调用)。
void cs_app_key(bsp_btn_t btn, bsp_btn_ev_t ev);
